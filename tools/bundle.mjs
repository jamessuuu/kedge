#!/usr/bin/env node
// A ~150 line bundler, and the reason it exists rather than a dependency.
//
// The demo has to be one static file a stranger can open from disk. ES modules
// do not load over file://, so the page needs a single classic <script>. Rather
// than add a build toolchain to a project whose whole argument is that it is
// verifiable, this walks the import graph and rewrites a deliberately tiny
// subset of module syntax:
//
//   import { a, b } from './x.js';   ->  const { a, b } = __req('x.js');
//   export function f              ->  function f          (+ registered)
//   export const C                 ->  const C             (+ registered)
//   export class K                 ->  class K             (+ registered)
//
// Anything else -- default exports, namespace imports, re-exports, dynamic
// import -- throws. A bundler that silently mis-handles a form it does not
// understand would be worse than no bundler, so this one refuses instead.
//
//   node tools/bundle.mjs           write web/kedge.bundle.js
//   node tools/bundle.mjs --check   fail if the committed bundle is stale

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '..');
const ENTRY = path.join(ROOT, 'web', 'app.js');
const OUT = path.join(ROOT, 'web', 'kedge.bundle.js');
const SAMPLE_LOGS = ['etcd_000.log', 'etcd_002.log'];

const IMPORT_RE = /^import\s*\{([^}]*)\}\s*from\s*['"]([^'"]+)['"];?\s*$/;
const EXPORT_FN_RE = /^export\s+(async\s+)?function\s+([A-Za-z_$][\w$]*)/;
const EXPORT_CONST_RE = /^export\s+(?:const|let|var)\s+([A-Za-z_$][\w$]*)/;
const EXPORT_CLASS_RE = /^export\s+class\s+([A-Za-z_$][\w$]*)/;

/**
 * @param {string} file absolute path
 * @param {Map<string, {id:string, code:string, deps:string[]}>} modules
 * @returns {string} module id
 */
function load(file, modules) {
  const id = path.relative(ROOT, file).split(path.sep).join('/');
  if (modules.has(id)) return id;
  const src = fs.readFileSync(file, 'utf8');
  const lines = src.split('\n');
  /** @type {string[]} */
  const deps = [];
  /** @type {string[]} */
  const exports = [];
  /** @type {string[]} */
  const out = [];

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    const trimmed = line.trim();

    if (trimmed.startsWith('import')) {
      const m = IMPORT_RE.exec(trimmed);
      if (!m) {
        throw new Error(
          id + ':' + (i + 1) + ': unsupported import form for this bundler:\n  ' + trimmed +
            '\nOnly `import { a, b } from \'./rel.js\';` is supported.'
        );
      }
      const spec = m[2];
      if (!spec.startsWith('.')) {
        throw new Error(id + ':' + (i + 1) + ': bare import "' + spec + '"; kedge has no runtime dependencies');
      }
      const depFile = path.resolve(path.dirname(file), spec);
      const depId = load(depFile, modules);
      deps.push(depId);
      out.push('const {' + m[1] + '} = __req(' + JSON.stringify(depId) + ');');
      continue;
    }

    if (trimmed.startsWith('export')) {
      let m;
      if ((m = EXPORT_FN_RE.exec(trimmed))) {
        exports.push(m[2]);
      } else if ((m = EXPORT_CLASS_RE.exec(trimmed))) {
        exports.push(m[1]);
      } else if ((m = EXPORT_CONST_RE.exec(trimmed))) {
        exports.push(m[1]);
      } else {
        throw new Error(
          id + ':' + (i + 1) + ': unsupported export form for this bundler:\n  ' + trimmed
        );
      }
      out.push(line.replace(/^(\s*)export\s+/, '$1'));
      continue;
    }
    out.push(line);
  }

  for (const name of exports) out.push('__exports.' + name + ' = ' + name + ';');
  modules.set(id, { id, code: out.join('\n'), deps });
  return id;
}

function buildSamples() {
  const dir = path.join(ROOT, 'vendor', 'porcupine', 'jepsen');
  const expected = JSON.parse(fs.readFileSync(path.join(ROOT, 'vendor', 'porcupine', 'expected.json'), 'utf8'));
  /** @type {any} */
  const samples = {};
  for (const file of SAMPLE_LOGS) {
    const row = expected.histories.find((/** @type {any} */ h) => h.file === file);
    if (!row) throw new Error('sample ' + file + ' is not in expected.json');
    samples[file] = { text: fs.readFileSync(path.join(dir, file), 'utf8'), expected: row.expected };
  }
  return samples;
}

function build() {
  /** @type {Map<string, {id:string, code:string, deps:string[]}>} */
  const modules = new Map();
  const entryId = load(ENTRY, modules);
  const samples = buildSamples();

  const parts = [];
  parts.push('// GENERATED by tools/bundle.mjs -- edit web/app.js or src/, then run `npm run build:web`.');
  parts.push('(function () {');
  parts.push('"use strict";');
  parts.push('var __defs = {};');
  parts.push('var __cache = {};');
  parts.push('function __req(id) {');
  parts.push('  if (__cache[id]) return __cache[id];');
  parts.push('  var m = { exports: {} };');
  parts.push('  __cache[id] = m.exports;');
  parts.push('  __defs[id](m.exports, __req);');
  parts.push('  return m.exports;');
  parts.push('}');
  parts.push('var KEDGE_SAMPLES = ' + JSON.stringify(samples) + ';');
  parts.push('if (typeof window !== "undefined") window.KEDGE_SAMPLES = KEDGE_SAMPLES;');
  for (const mod of modules.values()) {
    parts.push('__defs[' + JSON.stringify(mod.id) + '] = function (__exports, __req) {');
    parts.push(mod.code);
    parts.push('};');
  }
  parts.push('__req(' + JSON.stringify(entryId) + ');');
  parts.push('})();');
  return parts.join('\n') + '\n';
}

function main() {
  const checkOnly = process.argv.includes('--check');
  let bundle;
  try {
    bundle = build();
  } catch (err) {
    process.stderr.write('bundle: ' + /** @type {Error} */ (err).message + '\n');
    return 1;
  }
  if (checkOnly) {
    let current = null;
    try {
      current = fs.readFileSync(OUT, 'utf8');
    } catch {
      process.stderr.write('bundle: ' + path.relative(ROOT, OUT) + ' is missing; run `npm run build:web`\n');
      return 1;
    }
    if (current !== bundle) {
      process.stderr.write(
        'bundle: ' + path.relative(ROOT, OUT) + ' is stale; run `npm run build:web` and commit the result\n'
      );
      return 1;
    }
    process.stdout.write('bundle: up to date (' + bundle.length + ' bytes)\n');
    return 0;
  }
  fs.writeFileSync(OUT, bundle);
  process.stdout.write('bundle: wrote ' + path.relative(ROOT, OUT) + ' (' + bundle.length + ' bytes)\n');
  return 0;
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  process.exitCode = main();
}
